"""Indian numeral parser.

Finds and evaluates numbers written as digits (Latin, Devanagari, Kannada; Indian
grouping `1,00,000`; `4k`, `2.5 lakh`), English words (`one lakh twenty five
thousand`), Hindi words (`चार हज़ार`, `डेढ़ लाख`, `साढ़े तीन सौ`), Kannada words
(`ನಾಲ್ಕು ಸಾವಿರ`, `ಇಪ್ಪತ್ತೈದು`) and a core of romanised Hindi / Kannada
(`naalku saavira`, `char hazaar`).

Public API: `extract_numbers`, `parse_number`, `normalize_numbers`,
`extract_amounts`. See the module-level LIMITS note for what is not covered.

LIMITS (kept honest, tested where stated):
  * Romanised Hindi/Kannada covers 1-10, round tens and the multipliers only;
    compound romanised forms such as "pachees" or "ippattu aidu" are not parsed.
  * Kannada hundreds are covered (ನೂರು, ಇನ್ನೂರು..ಒಂಬೈನೂರು, "<unit> ನೂರು"),
    Kannada 21-99 are generated by the standard sandhi rule and tested on a sample.
  * A lone "one" / "do" is ignored (pronoun / verb) unless next to a currency word.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass
from fractions import Fraction

# ---------------------------------------------------------------------------
# Normalisation helpers
# ---------------------------------------------------------------------------

_DIGIT_TABLE = str.maketrans(
    "०१२३४५६७८९೦೧೨೩೪೫೬೭೮೯٠١٢٣٤٥٦٧٨٩",
    "012345678901234567890123456789",
)


def to_ascii_digits(text: str) -> str:
    """Map Devanagari/Kannada/Arabic-Indic digits to ASCII. Length preserving."""
    return text.translate(_DIGIT_TABLE)


def _norm_word(w: str) -> str:
    w = unicodedata.normalize("NFC", w).lower()
    w = w.replace("़", "")  # Devanagari nukta: हज़ार == हजार
    w = w.replace("ँ", "ं")  # chandrabindu -> anusvara: पाँच == पांच
    w = w.replace("‌", "").replace("‍", "")
    return w


# kind codes
UNIT, TEEN, TENS, TWO, HUND, HUNDRED, BIG, FRAC, PRE, AND, LIT = (
    "unit",
    "teen",
    "tens",
    "two",
    "hund",
    "hundred",
    "big",
    "frac",
    "pre",
    "and",
    "lit",
)

_LEX: dict[str, tuple[str, Fraction]] = {}


def _add(words: str | list[str], kind: str, value) -> None:
    if isinstance(words, str):
        words = words.split()
    for w in words:
        _LEX[_norm_word(w)] = (kind, Fraction(value))


def _add_seq(words: str, start: int, kind_for) -> None:
    for i, w in enumerate(words.split()):
        n = start + i
        for variant in w.split("/"):
            _add(variant, kind_for(n), n)


