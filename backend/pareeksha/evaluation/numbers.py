# Words that are also ordinary words; a run made only of one of them is ignored.
_WEAK = {"one", "do"}

_CUR_PRE = {"₹", "rs", "rs.", "inr", "रु", "रू", "ರೂ"}
_CUR_POST = {
    "rupees",
    "rupee",
    "rupaye",
    "rupaya",
    "rupya",
    "rupayi",
    "roopayi",
    "rs",
    "rs.",
    "inr",
    "रुपये",
    "रुपए",
    "रुपया",
    "रुपयों",
    "रुपय",
    "रू",
    "रु",
    "ರೂಪಾಯಿ",
    "ರೂಪಾಯಿಗಳು",
    "ರೂ",
    "ರೂಪಾಯಿಯನ್ನು",
}
_CUR_PRE_N = {_norm_word(w) for w in _CUR_PRE}
_CUR_POST_N = {_norm_word(w) for w in _CUR_POST}

_LITERAL = re.compile(
    r"^(\d+(?:,\d+)*(?:\.\d+)?)(k|lakh|lakhs|lac|lacs|cr|crore|crores)?$"
)
_SUFFIX = {
    "k": 1_000,
    "lakh": 100_000,
    "lakhs": 100_000,
    "lac": 100_000,
    "lacs": 100_000,
    "cr": 10_000_000,
    "crore": 10_000_000,
    "crores": 10_000_000,
}
_CUR_GLUE = re.compile(r"^(?:₹|rs\.?|inr)(?=\d)", re.IGNORECASE)
_EDGE = " \t\r\n.,;:!?()[]{}\"'“”‘’।|"


@dataclass(frozen=True)
class ParsedNumber:
    value: int | float
    start: int
    end: int
    text: str
    currency: bool = False
    literal_digits: bool = False  # plain digit string, left untouched by normalisation

    @property
    def canonical(self) -> str:
        if self.literal_digits:
            return self.text
        return _fmt(self.value)


def _fmt(v: float) -> str:
    return str(v)


def _num(fr: Fraction) -> int | float:
    return int(fr) if fr.denominator == 1 else float(fr)


@dataclass
class _Tok:
    start: int
    end: int
    kind: str
    value: Fraction
    glued_currency: bool = False
    literal_pure: bool = False
    word: str = ""


def _tokenize(text: str) -> list[_Tok | None]:
    """Return a list of tokens; non-number tokens are `None` (they split runs)."""
    src = to_ascii_digits(text)
    out: list[_Tok | None] = []
    for m in re.finditer(r"\S+", src):
        raw = m.group(0)
        s, e = m.start(), m.end()
        lstrip = len(raw) - len(raw.lstrip(_EDGE))
        core = raw.lstrip(_EDGE).rstrip(_EDGE)
        core = core.removesuffix("/-")
        if not core:
            out.append(None)
            continue
        s += lstrip
        e = s + len(core)
        glued = False
        g = _CUR_GLUE.match(core)
        if g:
            glued = True
            core = core[g.end() :]
            s = e - len(core)
        elif core.startswith("₹"):
            glued = True
            core = core[1:]
            s = e - len(core)
            if not core:
                out.append(_Tok(s, e, "cur", Fraction(0), word="₹"))
                continue
        low = _norm_word(core)
        lit = _LITERAL.match(low)
        if lit:
            val = Fraction(lit.group(1).replace(",", ""))
            if lit.group(2):
                val *= _SUFFIX[lit.group(2)]
            out.append(
                _Tok(
                    s,
                    e,
                    LIT,
                    val,
                    glued_currency=glued,
                    literal_pure=bool(re.fullmatch(r"\d+", low)),
                    word=low,
                )
            )
            continue
        hit = _LEX.get(low) or _LEX.get(low.replace("-", ""))
        if hit:
            out.append(_Tok(s, e, hit[0], hit[1], glued_currency=glued, word=low))
            continue
        if "-" in low:
            parts = [_LEX.get(p) for p in low.split("-")]
            resolved = [p for p in parts if p is not None]
            if len(resolved) == len(parts):
                for p, word in zip(resolved, low.split("-")):
                    out.append(_Tok(s, e, p[0], p[1], glued_currency=glued, word=word))
                continue
        out.append(
            _Tok(s, e, "cur", Fraction(0), word=low)
            if low in _CUR_PRE_N | _CUR_POST_N
            else None
        )
    return out


_SMALL = {UNIT, TEEN, TWO, LIT, FRAC, HUND}


def _can_extend(last: str | None, tok: _Tok, last_big: Fraction | None) -> bool:
    k = tok.kind
    if last is None:
        return k not in (BIG, AND, "cur")
    if k in (UNIT, TEEN, TWO, TENS, LIT, FRAC, HUND):
        if last == TENS:
            return k == UNIT and tok.value > 0
        if last == HUND:
            return k in (UNIT, TEEN, TWO, TENS)
        if last == PRE:
            return k in (UNIT, TEEN, TWO, LIT)
        return last in (HUNDRED, BIG)
    if k == HUNDRED:
        return last in (UNIT, TEEN, TWO, TENS, LIT, FRAC, PRE)
    if k == BIG:
        if last == PRE:
            return True
        if last not in (UNIT, TEEN, TWO, TENS, LIT, FRAC, HUND, HUNDRED):
            return False
        return last_big is None or tok.value < last_big
    return False


def _eval_run(run: list[_Tok]) -> Fraction | None:
    total = Fraction(0)
    cur = Fraction(0)
    pre = Fraction(0)
    for t in run:
        k = t.kind
        if k == PRE:
            pre = t.value
        elif k in (UNIT, TEEN, TWO, TENS, LIT, FRAC, HUND):
            cur += t.value + pre
            pre = Fraction(0)
        elif k == HUNDRED:
            cur = (cur or Fraction(1)) * 100
        elif k == BIG:
            if pre:
                cur, pre = Fraction(1) + pre, Fraction(0)
            if cur == 0:
                return None
            total += cur * t.value
            cur = Fraction(0)
    if pre:
        return None
    return total + cur


def extract_numbers(text: str) -> list[ParsedNumber]:
    """All numbers in `text` in order, with character spans into the original text."""
    toks = _tokenize(text)
    results: list[ParsedNumber] = []
    i, n = 0, len(toks)
    while i < n:
        t = toks[i]
        if (
            t is None
            or t.kind == "cur"
            or t.kind == AND
            or not _can_extend(None, t, None)
        ):
            i += 1
            continue
        run = [t]
        last, last_big = t.kind, None
        j = i + 1
        while j < n:
            nt = toks[j]
            if nt is None:
                break
            if nt.kind == AND:  # "one hundred and five"
                nxt = toks[j + 1] if j + 1 < n else None
                if (
                    last in (HUNDRED, BIG)
                    and nxt
                    and nxt.kind in (UNIT, TEEN, TWO, TENS, LIT)
                    and _can_extend(last, nxt, last_big)
                ):
                    j += 1
                    continue
                break
            if not _can_extend(last, nt, last_big):
                break
            if nt.kind == BIG:
                last_big = nt.value
            run.append(nt)
            last = nt.kind
            j += 1
        value = _eval_run(run)
        prev = toks[i - 1] if i > 0 else None
        nxt_tok = toks[j] if j < n else None
        currency = (
            any(r.glued_currency for r in run)
            or bool(prev and prev.kind == "cur" and prev.word in _CUR_PRE_N)
            or bool(nxt_tok and nxt_tok.kind == "cur" and nxt_tok.word in _CUR_POST_N)
        )
        weak_single = len(run) == 1 and run[0].word in _WEAK
        if value is not None and not (weak_single and not currency):
            start, end = run[0].start, run[-1].end
            literal = len(run) == 1 and run[0].literal_pure
            results.append(
                ParsedNumber(
                    _num(value),
                    start,
                    end,
                    text[start:end],
                    currency=currency,
                    literal_digits=literal,
                )
            )
        i = j if j > i else i + 1
    return results


def extract_amounts(text: str) -> list[ParsedNumber]:
    """Numbers that are explicitly money (₹ / Rs / rupees / रुपये / ರೂಪಾಯಿ)."""
    return [n for n in extract_numbers(text) if n.currency]


def parse_number(text: str) -> int | float | None:
    """Value of `text` if it is exactly one number (optionally with a currency word)."""
    found = extract_numbers(text)
    if len(found) != 1:
        return None
    n = found[0]
    rest = text[: n.start] + " " + text[n.end :]
    toks = [_norm_word(x.strip(_EDGE)) for x in rest.split()]
    toks = [
        x
        for x in toks
        if x and x not in _CUR_PRE_N and x not in _CUR_POST_N and x != "/-"
    ]
    if toks:
        return None
    return n.value


def normalize_numbers(text: str) -> str:
    """Replace every parsed number with canonical ASCII digits (no separators)."""
    out = text
    for n in reversed(extract_numbers(text)):
        if n.literal_digits:
            repl = to_ascii_digits(n.text)
        else:
            repl = n.canonical
        out = out[: n.start] + repl + out[n.end :]
    return out
