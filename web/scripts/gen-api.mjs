#!/usr/bin/env node
// Generates lib/api/schema.d.ts from the backend OpenAPI document (FR-DB-6).
//
//   npm run gen:api                      # from OPENAPI_URL or http://localhost:8000/openapi.json
//   npm run gen:api -- --from <file|url> # explicit source
//   npm run gen:api:check                # regenerate in memory, exit 1 if schema.d.ts differs (CI staleness gate)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../lib/api/schema.d.ts");

const args = process.argv.slice(2);
const check = args.includes("--check");
const fromIdx = args.indexOf("--from");
const source = fromIdx >= 0 ? args[fromIdx + 1] : (process.env.OPENAPI_URL ?? "http://localhost:8000/openapi.json");
if (!source) {
  console.error("--from requires a value");
  process.exit(2);
}

const input = /^https?:\/\//.test(source) ? new URL(source) : pathToFileURL(resolve(source));
let ast;
try {
  ast = await openapiTS(input);
} catch (err) {
  console.error(`gen:api failed to read OpenAPI from ${source}: ${err instanceof Error ? err.message : err}`);
  process.exit(1);
}
const banner = "/* GENERATED by scripts/gen-api.mjs from the backend OpenAPI document. Do not edit. */\n";
const generated = banner + astToString(ast);

if (check) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    // missing file counts as stale
  }
  if (current !== generated) {
    console.error("lib/api/schema.d.ts is stale. Run `npm run gen:api` and commit the result.");
    process.exit(1);
  }
  console.log("lib/api/schema.d.ts is up to date.");
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, generated);
  console.log(`Wrote ${out} from ${source}`);
}
